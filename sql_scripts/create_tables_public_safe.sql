-- Every statement uses IF NOT EXISTS: a table that already exists is left
-- untouched (PostgreSQL prints a harmless 'skipping' notice). No table or
-- data is ever dropped. Safe to re-run any number of times.

CREATE TABLE IF NOT EXISTS accounts (
    account_number                             VARCHAR(32) NOT NULL,
    customer_cif                               VARCHAR(32),
    customer_branch_ifsc                       VARCHAR(32),
    account_category                           VARCHAR(32),
    account_type                               VARCHAR(32),
    account_status                             VARCHAR(32),
    account_opening_date                       DATE,
    inoperative_status_date                    DATE,
    credit_summation_period                    NUMERIC(20,2),
    debit_summation_period                     NUMERIC(20,2),
    PRIMARY KEY (account_number)
);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS loaded_at TIMESTAMPTZ DEFAULT now();
CREATE INDEX IF NOT EXISTS idx_accounts_customer_cif ON accounts (customer_cif);
CREATE INDEX IF NOT EXISTS idx_accounts_account_status ON accounts (account_status);

